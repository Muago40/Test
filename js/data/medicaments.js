// Index de recherche : nom normalisé → médicament
export function normaliser(s) {
  return (s || "")
    .toLowerCase()
    .normalize("NFD").replace(/[̀-ͯ]/g, "")
    .replace(/[^a-z0-9/ -]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

export function trouverParId(id) {
  return MEDICAMENTS.find((m) => m.id === id) || null;
}
